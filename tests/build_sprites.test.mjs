// The generated js/sprites.js must be reproducible and up to date. Run: node --test
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const script = new URL('../scripts/build-sprites.mjs', import.meta.url).pathname;
const committed = new URL('../js/sprites.js', import.meta.url).pathname;

test('build-sprites is deterministic and matches the committed js/sprites.js', () => {
  const dir = mkdtempSync(join(tmpdir(), 'sprites-'));
  try {
    const a = join(dir, 'a.js');
    const b = join(dir, 'b.js');
    execFileSync('node', [script, '--out', a]);
    execFileSync('node', [script, '--out', b]);
    assert.equal(readFileSync(a, 'utf8'), readFileSync(b, 'utf8'));
    assert.equal(readFileSync(a, 'utf8'), readFileSync(committed, 'utf8'), 'js/sprites.js is stale: run node scripts/build-sprites.mjs');
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test('generated file has the header and the PNG data URLs', async () => {
  const src = readFileSync(committed, 'utf8');
  assert.match(src.split('\n')[0], /GENERATED by scripts\/build-sprites\.mjs — do not edit/);
  const mod = await import('../js/sprites.js');
  for (const k of ['SHEET_URL', 'ALICE_URL', 'BOB_URL']) {
    assert.match(mod[k], /^data:image\/png;base64,iVBORw0KGgo/, k);
  }
});

test('generated file embeds the decoration atlas (DECOR_URL) and its frames (DECOR_FRAMES)', async () => {
  const mod = await import('../js/sprites.js');
  assert.match(mod.DECOR_URL, /^data:image\/png;base64,iVBORw0KGgo/);
  const atlasPng = readFileSync(new URL('../assets/lab_decorations_atlas.png', import.meta.url));
  assert.equal(mod.DECOR_URL, `data:image/png;base64,${atlasPng.toString('base64')}`);
  const frames = JSON.parse(readFileSync(new URL('../assets/lab_decorations_atlas.json', import.meta.url), 'utf8'));
  assert.deepEqual(mod.DECOR_FRAMES, frames);
  for (const name of ['tank_chick', 'tank_jelly', 'plant', 'rug', 'grate', 'wall_light']) {
    const f = mod.DECOR_FRAMES[name];
    assert.ok(f, name);
    assert.ok(Number.isInteger(f.x) && Number.isInteger(f.y) && f.w > 0 && f.h > 0, name);
    const [fw, fh] = f.footprint;
    assert.ok(f.w <= fw * 32 && f.h <= fh * 32, `${name} fits its footprint at 2x`);
    assert.ok(f.w === fw * 32 || f.h === fh * 32, `${name} fills one footprint axis`);
  }
});

test('js/sprites.js stays far below the 2 MB Qollab per-file limit', () => {
  const size = readFileSync(committed).length;
  assert.ok(size < 512 * 1024, `js/sprites.js is ${size} bytes`);
});
