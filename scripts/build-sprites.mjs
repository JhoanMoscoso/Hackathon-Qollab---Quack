#!/usr/bin/env node
// Embeds the sprite PNGs and the theme registries as base64 data URLs / JSON in js/sprites.js (Qollab cannot load project files at runtime).
// Usage: node scripts/build-sprites.mjs [--out path]
// Deterministic: same PNGs in, same bytes out. Re-run after changing anything under assets/.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outIdx = process.argv.indexOf('--out');
const out = outIdx > 0 ? resolve(process.argv[outIdx + 1]) : resolve(root, 'js/sprites.js');

const INPUTS = [
  ['ALICE_URL', 'assets/characters/alice_walk_4dir.png'],
  ['BOB_URL', 'assets/characters/bob_walk_4dir.png'],
];
// Themed sheets sliced from the AI art by scripts/slice-themes.sh: assets/themes/<theme>_{tiles,props}.png + <theme>.json.
const THEME_NAMES = ['lab', 'prison', 'core'];

const lines = ['// GENERATED by scripts/build-sprites.mjs — do not edit. Source: assets/ (run the script to refresh).'];
for (const [name, rel] of INPUTS) {
  const png = readFileSync(resolve(root, rel));
  lines.push(`export const ${name} = 'data:image/png;base64,${png.toString('base64')}';`);
}
const themes = {};
for (const name of THEME_NAMES) {
  const reg = JSON.parse(readFileSync(resolve(root, `assets/themes/${name}.json`), 'utf8'));
  const url = (kind) => `data:image/png;base64,${readFileSync(resolve(root, `assets/themes/${name}_${kind}.png`)).toString('base64')}`;
  themes[name] = { tilesUrl: url('tiles'), propsUrl: url('props'), wallTopColor: reg.wall_top_color, tiles: reg.tiles, props: reg.props };
}
lines.push(`export const THEMES = ${JSON.stringify(themes)};`);
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`wrote ${out} (${lines.join('\n').length + 1} bytes)`);
